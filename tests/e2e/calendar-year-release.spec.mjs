import {test,expect} from "@playwright/test";

test("2027 race calendar displays dates and supports filters without opening entry",async({page})=>{
  await page.setViewportSize({width:390,height:844});
  const errors=[];page.on("pageerror",error=>errors.push(error.message));
  await page.goto("/login");
  await page.getByLabel("Email or username").fill("alice");
  await page.getByLabel("Password").fill("fixture-password");
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  await expect(page).toHaveURL(/\/team$/);
  await page.getByRole("link",{name:"2027 calendar plan"}).click();
  await expect(page.getByRole("heading",{name:"Pelotonia Year 1"})).toBeVisible();
  await expect(page.getByText("Santos Tour Down Under",{exact:true})).toHaveCount(2);
  await expect(page.getByText("19 Jan – 24 Jan",{exact:true})).toBeVisible();
  await page.getByLabel("Field").selectOption("Women");
  await page.getByLabel("Format").selectOption("stage");
  await page.getByLabel("Class").selectOption("SILVER");
  await expect(page.getByText("Santos Tour Down Under",{exact:true})).toHaveCount(1);
  await expect(page.getByText("22 Jan – 24 Jan",{exact:true})).toBeVisible();
  await page.getByLabel("Field").selectOption("");
  await page.getByLabel("Format").selectOption("");
  await page.getByLabel("Class").selectOption("");
  await page.getByRole("button",{name:/YEAR 2/}).click();
  await expect(page.getByRole("heading",{name:"Pelotonia Year 2"})).toBeVisible();
  await page.getByRole("button",{name:/June/}).click();
  await expect(page.getByRole("heading",{name:/June 2027/})).toBeVisible();
  await expect(page.getByRole("listitem").filter({hasText:"Tour de Suisse"}).first()).toBeVisible();
  await expect(page.getByRole("link",{name:/Set up|Register/})).toHaveCount(0);
  await expect(page.getByText("Milano-Sanremo")).toHaveCount(0);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  await page.setViewportSize({width:1280,height:800});
  await page.getByRole("button",{name:/YEAR 1/}).click();
  await page.evaluate(()=>{document.activeElement?.blur();window.scrollTo(0,0);});
  await page.screenshot({path:"test-results/calendar-2027-desktop.png",fullPage:true});
});
